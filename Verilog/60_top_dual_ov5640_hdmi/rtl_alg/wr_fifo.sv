module wr_fifo (
    input  wire         rst,
    input  wire         wr_clk,
    input  wire         rd_clk,
    input  wire [127:0] din,
    input  wire         wr_en,
    input  wire         rd_en,
    output wire [127:0] dout,
    output wire         full,
    output wire         empty,
    output wire [8:0]   rd_data_count,
    output wire [8:0]   wr_data_count,
    output wire         wr_rst_busy,
    output wire         rd_rst_busy
);
    xpm_fifo_async #(
        .FIFO_MEMORY_TYPE    ("block"),
        .FIFO_WRITE_DEPTH    (512),
        .WRITE_DATA_WIDTH    (128),
        .WR_DATA_COUNT_WIDTH (9),
        .USE_ADV_FEATURES    ("0000"),
        .READ_MODE           ("fwft"),
        .FIFO_READ_LATENCY   (0),
        .READ_DATA_WIDTH     (128),
        .RD_DATA_COUNT_WIDTH (9),
        .CDC_SYNC_STAGES     (2),
        .RELATED_CLOCKS      (0)
    ) u_xpm_fifo_async (
        .sleep          (1'b0),
        .rst            (rst),
        .wr_clk         (wr_clk),
        .wr_en          (wr_en),
        .din            (din),
        .full           (full),
        .prog_full      (),
        .wr_data_count  (wr_data_count),
        .overflow       (),
        .wr_rst_busy    (wr_rst_busy),
        .almost_full    (),
        .wr_ack         (),
        .rd_clk         (rd_clk),
        .rd_en          (rd_en),
        .dout           (dout),
        .empty          (empty),
        .prog_empty     (),
        .rd_data_count  (rd_data_count),
        .underflow      (),
        .rd_rst_busy    (rd_rst_busy),
        .almost_empty   (),
        .data_valid     (),
        .injectsbiterr  (1'b0),
        .injectdbiterr  (1'b0),
        .sbiterr        (),
        .dbiterr        ()
    );
endmodule
